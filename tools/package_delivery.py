"""Build the delivery archive and verify it can be used without this workspace.

Processed arrays and trained checkpoints are left out because they are large and
every one of them is regenerated by the delivered scripts from the delivered raw
files. Everything needed to read the paper, inspect a number, or rerun the
pipeline from scratch is included.
"""
from __future__ import annotations

import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "dyhgt_marl.zip"

INCLUDE_TREES = ["configs", "src", "scripts", "tools", "docs", "data/raw"]
INCLUDE_RESULTS = ["results/tables", "results/tables_kl", "results/tables_stress",
                   "results/figures"]
INCLUDE_FILES = ["README.md", "requirements.txt", "environment.yml",
                 "Makefile", "run_all.py"]
SKIP_SUFFIX = {".pyc", ".pt", ".npy"}
SKIP_DIR_PARTS = {"__pycache__", ".ipynb_checkpoints"}


def wanted(p: pathlib.Path) -> bool:
    if not p.is_file():
        return False
    if p.suffix in SKIP_SUFFIX:
        return False
    return not (set(p.parts) & SKIP_DIR_PARTS)


def main() -> None:
    members: list[pathlib.Path] = []
    for tree in INCLUDE_TREES + INCLUDE_RESULTS:
        d = ROOT / tree
        if d.is_dir():
            members += [p for p in d.rglob("*") if wanted(p)]
    for name in INCLUDE_FILES:
        p = ROOT / name
        if p.is_file():
            members.append(p)
    members += [p for p in ROOT.glob("*_Full_Paper.docx")]
    members += [p for p in ROOT.glob("*_Math_Reference.pdf")]
    # the IEEE Access submission file and the template it is built from
    members += [p for p in ROOT.glob("DyHGT_IEEE_Access_Submission.docx")]
    members += [p for p in (ROOT / "assets").glob("*.docx")]

    if OUT.exists():
        OUT.unlink()
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for p in sorted(set(members)):
            z.write(p, pathlib.Path("dyhgt_marl") / p.relative_to(ROOT))

    with zipfile.ZipFile(OUT) as z:
        names = z.namelist()
    print(f"wrote {OUT.name}: {len(names)} files, "
          f"{OUT.stat().st_size / 1e6:.1f} MB")
    for must in ("dyhgt_marl/README.md",
                 "dyhgt_marl/docs/manuscript.md",
                 "dyhgt_marl/docs/SUBMISSION_CHECKLIST.md",
                 "dyhgt_marl/src/dyhgt/stress.py",
                 "dyhgt_marl/scripts/run_experiment_g_budget.py",
                 "dyhgt_marl/scripts/check_early_stopping_effect.py",
                 "dyhgt_marl/tools/audit_delivery.py",
                 "dyhgt_marl/run_all.py",
                 "dyhgt_marl/Makefile",
                 "dyhgt_marl/docs/REPRODUCTION.md",
                 "dyhgt_marl/results/tables/table_14_stress_regime.csv",
                 "dyhgt_marl/results/figures/fig_15_stress_regime.pdf",
                 "dyhgt_marl/data/raw/hcmc_traffic_data.csv"):
        print(f"  {'ok  ' if must in names else 'MISS'} {must}")
    n_fig = len([n for n in names if n.endswith(".pdf") and "/figures/" in n])
    n_tab = len([n for n in names if "/tables" in n and n.endswith(".csv")])
    print(f"  figures: {n_fig} pdf, result and table csv files: {n_tab}")


if __name__ == "__main__":
    main()
